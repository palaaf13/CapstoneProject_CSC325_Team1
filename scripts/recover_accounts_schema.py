"""Safely reconcile accounts.0001_initial's MongoDB collections and indexes.

Default mode is read-only. Writes require both --write and
--confirm-accounts-schema-recovery. This script never changes migration history.
"""

from __future__ import annotations

import argparse
import os
import pprint
import sys
from collections.abc import Mapping
from pathlib import Path


TARGET_DATABASE = "ramhub"
EXPECTED_MIGRATION = ("accounts", "0001_initial")
TARGET_COLLECTION_NAMES = (
    "accounts_user",
    "accounts_user_groups",
    "accounts_user_user_permissions",
)
CONFIRM_FLAG = "--confirm-accounts-schema-recovery"


class RecoveryError(Exception):
    """A safe preflight or verification failure with non-sensitive details."""


def canonical(value):
    """Normalize BSON/document values for exact, order-aware index comparison."""
    if isinstance(value, Mapping):
        return tuple(sorted((key, canonical(item)) for key, item in value.items()))
    if isinstance(value, (list, tuple)):
        return tuple(canonical(item) for item in value)
    return value


def printable(value):
    """Render expected specs without ever rendering connection credentials."""
    if isinstance(value, Mapping):
        return {key: printable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [printable(item) for item in value]
    if value.__class__.__name__ == "ObjectId":
        return f'ObjectId("{value}")'
    return value


def normalized_index(index_document):
    name = index_document.get("name")
    key = tuple(index_document.get("key", {}).items())
    options = {
        key: value
        for key, value in index_document.items()
        if key not in {"v", "ns", "key", "name"}
    }
    unique = bool(options.pop("unique", False))
    # MongoDB's mandatory _id_ index is unique even when listIndexes omits the
    # unique option from its returned document.
    if name == "_id_":
        unique = True
    return name, key, unique, canonical(options)


def index_document(index_model):
    return dict(index_model.document)


def collect_backend_indexes(schema_editor, model):
    """Capture exact IndexModels generated by the installed schema editor.

    `_create_model_indexes()` is private in django-mongodb-backend 6.1.0.
    Its source was inspected: it derives field, unique_together, constraint,
    and Meta.indexes specs and sends them to Collection.create_indexes().
    Here get_collection() is temporarily replaced with a recorder so the
    backend builds those exact specs without writing them.
    """
    captured = []

    class CollectionRecorder:
        def create_indexes(self, indexes):
            captured.extend(indexes)

        def create_search_index(self, index):
            raise RecoveryError(
                f"Unexpected search index on {model._meta.db_table}; stopping."
            )

    original_get_collection = schema_editor.get_collection
    schema_editor.get_collection = lambda name: CollectionRecorder()
    try:
        schema_editor._create_model_indexes(model)
    finally:
        schema_editor.get_collection = original_get_collection

    by_name = {index.document["name"]: index for index in captured}
    if len(by_name) != len(captured):
        raise RecoveryError(
            f"Backend generated duplicate index names for {model._meta.db_table}."
        )

    # MongoDB creates this mandatory primary-key index when a collection is
    # created. It is not emitted by _create_model_indexes().
    expected_documents = {
        "_id_": {"key": {"_id": 1}, "name": "_id_", "unique": True}
    }
    expected_documents.update(
        {name: index_document(index) for name, index in by_name.items()}
    )
    return by_name, expected_documents


def expected_models(connection, schema_editor):
    """Load models from the historical migration state, not current models."""
    from django.db.migrations.loader import MigrationLoader

    state = MigrationLoader(None).project_state([EXPECTED_MIGRATION])
    historical_apps = state.apps
    user_model = historical_apps.get_model("accounts", "User")
    groups_model = user_model._meta.get_field("groups").remote_field.through
    permissions_model = user_model._meta.get_field(
        "user_permissions"
    ).remote_field.through

    models = {
        "accounts_user": user_model,
        "accounts_user_groups": groups_model,
        "accounts_user_user_permissions": permissions_model,
    }
    if tuple(models) != TARGET_COLLECTION_NAMES:
        raise RecoveryError("Historical collection names differ from the reviewed plan.")
    for name, model in models.items():
        if model._meta.db_table != name:
            raise RecoveryError(
                f"Historical table for {name} resolved unexpectedly; stopping."
            )
    if groups_model._meta.local_many_to_many or permissions_model._meta.local_many_to_many:
        raise RecoveryError("A through model has nested relations; stopping safely.")

    expected = {}
    for name, model in models.items():
        generated, documents = collect_backend_indexes(schema_editor, model)
        expected[name] = {
            "model": model,
            "index_models": generated,
            "index_documents": documents,
        }
    return expected


def collection_metadata(database, name):
    entries = list(database.list_collections(filter={"name": name}))
    return entries[0] if entries else None


def duplicate_group_count(collection, fields):
    grouped_key = {field: f"${field}" for field in fields}
    pipeline = [
        {"$group": {"_id": grouped_key, "document_count": {"$sum": 1}}},
        {"$match": {"document_count": {"$gt": 1}}},
        {"$count": "duplicate_groups"},
    ]
    result = list(collection.aggregate(pipeline))
    return result[0]["duplicate_groups"] if result else 0


def validate_document_types(collection, name, model, document_count):
    """Ensure all existing documents fall within the intended index filters."""
    if not document_count:
        return

    if name == "accounts_user":
        fields = (("username", "string"), ("email", "string"))
    elif name == "accounts_user_groups":
        fields = (("user_id", "objectId"), ("group_id", "objectId"))
    else:
        fields = (("user_id", "objectId"), ("permission_id", "objectId"))

    for field_name, bson_type in fields:
        valid_count = collection.count_documents(
            {field_name: {"$type": bson_type}}
        )
        if valid_count != document_count:
            raise RecoveryError(
                f"{name} has {document_count - valid_count} documents with a "
                f"missing or non-{bson_type} {field_name}; stopping before writes."
            )

    if name == "accounts_user":
        unique_fields = (("username",), ("email",))
    elif name == "accounts_user_groups":
        unique_fields = (("user_id", "group_id"),)
    else:
        unique_fields = (("user_id", "permission_id"),)

    for fields_to_check in unique_fields:
        duplicates = duplicate_group_count(collection, fields_to_check)
        if duplicates:
            label = ", ".join(fields_to_check)
            raise RecoveryError(
                f"{name} has {duplicates} duplicate groups for ({label}); "
                "the required unique index cannot be created. No values were printed."
            )


def inspect_collection(database, name, expected, collection_names):
    if name not in collection_names:
        if name == "accounts_user":
            raise RecoveryError(
                "accounts_user is missing; refusing to create or replace the "
                "collection that this recovery is required to preserve."
            )
        return {
            "exists": False,
            "document_count": 0,
            "indexes": {},
            "missing_indexes": sorted(expected[name]["index_documents"]),
        }

    metadata = collection_metadata(database, name)
    if metadata is None or metadata.get("type") != "collection":
        raise RecoveryError(f"{name} is not a normal collection; stopping.")
    options = metadata.get("options", {})
    if options:
        raise RecoveryError(
            f"{name} has unexpected collection options; stopping without changes."
        )

    collection = database[name]
    document_count = collection.count_documents({})
    if document_count != 0:
        raise RecoveryError(
            f"{name} contains {document_count} document(s); expected zero. "
            "Stopping before any write; document contents were not printed."
        )
    validate_document_types(collection, name, expected[name]["model"], document_count)

    actual_documents = list(collection.list_indexes())
    expected_documents = expected[name]["index_documents"]
    actual_by_name = {document.get("name"): document for document in actual_documents}
    if len(actual_by_name) != len(actual_documents):
        raise RecoveryError(f"{name} returned duplicate index names; stopping.")

    for index_name, actual in actual_by_name.items():
        if index_name not in expected_documents:
            raise RecoveryError(
                f"{name} has unexpected index {index_name!r}; stopping rather "
                "than modifying or replacing it."
            )
        if normalized_index(actual) != normalized_index(expected_documents[index_name]):
            raise RecoveryError(
                f"{name} index {index_name!r} conflicts with the historical "
                "index definition; stopping rather than modifying it."
            )

    missing = sorted(set(expected_documents) - set(actual_by_name))
    return {
        "exists": True,
        "document_count": document_count,
        "indexes": actual_by_name,
        "missing_indexes": missing,
    }


def print_expected_indexes(expected):
    print("Expected index definitions (generated from historical models/backend):")
    for collection_name in TARGET_COLLECTION_NAMES:
        print(f"  {collection_name}:")
        for index_name in sorted(expected[collection_name]["index_documents"]):
            document = expected[collection_name]["index_documents"][index_name]
            print("    " + pprint.pformat(printable(document), sort_dicts=False))


def print_inventory(title, expected, inventory):
    print(title)
    for name in TARGET_COLLECTION_NAMES:
        item = inventory[name]
        if not item["exists"]:
            print(f"  {name}: absent; planned collection creation")
            print(f"    planned indexes: {', '.join(item['missing_indexes'])}")
            continue
        existing_names = sorted(item["indexes"])
        print(
            f"  {name}: exists; documents={item['document_count']}; "
            f"indexes={existing_names}"
        )
        print(
            f"    missing expected indexes: "
            f"{item['missing_indexes'] or 'none'}"
        )


def inspect_all(database, expected):
    collection_names = set(database.list_collection_names())
    return {
        name: inspect_collection(database, name, expected, collection_names)
        for name in TARGET_COLLECTION_NAMES
    }


def index_model_for_document(document):
    from pymongo import IndexModel

    options = {
        key: value
        for key, value in document.items()
        if key not in {"key", "name"}
    }
    return IndexModel(document["key"], **options)


def verify_counts_unchanged(before, after):
    for name in TARGET_COLLECTION_NAMES:
        if after[name]["document_count"] != before[name]["document_count"]:
            raise RecoveryError(
                f"{name} document count changed during recovery; stopping immediately."
            )


def apply_recovery(database, schema_editor, expected, initial_inventory):
    inventory = initial_inventory

    # Never call create_model(User): accounts_user already exists, and the
    # backend's create_model() unconditionally calls create_collection().
    for name in TARGET_COLLECTION_NAMES:
        item = inventory[name]
        model = expected[name]["model"]

        if not item["exists"]:
            if name == "accounts_user":
                raise RecoveryError("Refusing to create accounts_user.")
            print(f"Creating missing collection {name} through the schema editor.")
            schema_editor.create_model(model)
            inventory = inspect_all(database, expected)
            verify_counts_unchanged(initial_inventory, inventory)
            if not inventory[name]["exists"] or inventory[name]["missing_indexes"]:
                raise RecoveryError(
                    f"{name} did not reach its complete expected schema; stopping."
                )
            print_inventory(f"Verified after creating {name}:", expected, inventory)
            continue

        for index_name in item["missing_indexes"]:
            if index_name == "_id_":
                raise RecoveryError(
                    f"{name} lacks MongoDB's mandatory _id_ index; stopping."
                )
            # Reinspect immediately before each index write. This detects
            # changes since preflight and ensures only a missing index is sent.
            inventory = inspect_all(database, expected)
            verify_counts_unchanged(initial_inventory, inventory)
            current = inventory[name]
            if not current["exists"]:
                raise RecoveryError(f"{name} disappeared during recovery; stopping.")
            if index_name not in current["missing_indexes"]:
                continue

            print(f"Creating missing index {index_name} on {name}.")
            index_model = expected[name]["index_models"].get(index_name)
            if index_model is None:
                index_model = index_model_for_document(
                    expected[name]["index_documents"][index_name]
                )
            # This is the same PyMongo Collection.create_indexes() operation
            # used by the installed backend's schema editor for index creation.
            schema_editor.get_collection(name).create_indexes([index_model])

            inventory = inspect_all(database, expected)
            verify_counts_unchanged(initial_inventory, inventory)
            if index_name in inventory[name]["missing_indexes"]:
                raise RecoveryError(
                    f"Index {index_name} was not visible after creation; stopping."
                )
            print_inventory(f"Verified after creating {index_name}:", expected, inventory)

    final_inventory = inspect_all(database, expected)
    verify_counts_unchanged(initial_inventory, final_inventory)
    for name, item in final_inventory.items():
        if not item["exists"] or item["missing_indexes"]:
            raise RecoveryError(f"Final schema verification failed for {name}.")
    return final_inventory


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write",
        action="store_true",
        help="Create only missing expected collections/indexes (requires confirmation).",
    )
    parser.add_argument(
        CONFIRM_FLAG,
        action="store_true",
        help="Explicitly confirm the physical schema recovery write mode.",
    )
    args = parser.parse_args(argv)
    if args.write and not getattr(args, CONFIRM_FLAG[2:].replace("-", "_")):
        parser.error(f"--write requires {CONFIRM_FLAG}")
    if not args.write and getattr(args, CONFIRM_FLAG[2:].replace("-", "_")):
        parser.error(f"{CONFIRM_FLAG} requires --write")
    return args


def run(argv=None):
    args = parse_args(argv)

    root = Path(__file__).resolve().parents[1]
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))
    requested_settings = os.environ.get("DJANGO_SETTINGS_MODULE")
    if requested_settings not in (None, "config.settings.dev"):
        raise RecoveryError(
            "This recovery script only permits config.settings.dev; refusing "
            "an alternate settings module."
        )
    os.environ["DJANGO_SETTINGS_MODULE"] = "config.settings.dev"

    import django
    import django_mongodb_backend
    from django.conf import settings
    from django.db import connections

    if django.VERSION[:3] != (6, 1, 1):
        raise RecoveryError("Expected Django 6.1.1; refusing a different version.")
    if django_mongodb_backend.__version__ != "6.1.0":
        raise RecoveryError(
            "Expected django-mongodb-backend 6.1.0; refusing a different version."
        )

    database_settings = settings.DATABASES["default"]
    if database_settings.get("NAME") != TARGET_DATABASE:
        raise RecoveryError(
            f"Configured database name is not {TARGET_DATABASE!r}; refusing to connect."
        )

    mode = "WRITE (explicitly confirmed)" if args.write else "DRY RUN (read-only)"
    print(f"Target database: {TARGET_DATABASE}")
    print("Target collections:")
    for name in TARGET_COLLECTION_NAMES:
        print(f"  - {name}")
    print(f"Mode: {mode}")
    print("Migration recorder/history: not read or modified by this script.")

    django.setup()
    connection = connections["default"]
    connection.ensure_connection()
    database = connection.get_database()
    if database.name != TARGET_DATABASE:
        raise RecoveryError("Connected database name differs from the required target.")

    with connection.schema_editor(atomic=False) as schema_editor:
        expected = expected_models(connection, schema_editor)
        print_expected_indexes(expected)

        before = inspect_all(database, expected)
        print_inventory("Before recovery:", expected, before)

        if not args.write:
            changes = []
            for name in TARGET_COLLECTION_NAMES:
                item = before[name]
                if not item["exists"]:
                    changes.append(f"create collection {name} with schema-editor indexes")
                else:
                    changes.extend(
                        f"create index {index_name} on {name}"
                        for index_name in item["missing_indexes"]
                        if index_name != "_id_"
                    )
            print("Dry-run plan:")
            print("  " + ("\n  ".join(changes) if changes else "No changes required."))
            print("Dry run complete; no collections, indexes, or documents were changed.")
            return 0

        final = apply_recovery(database, schema_editor, expected, before)
        print_inventory("Final verified schema:", expected, final)
        print("Recovery complete. No documents or migration-history records were changed.")
        return 0


if __name__ == "__main__":
    try:
        raise SystemExit(run())
    except RecoveryError as exc:
        print(f"RECOVERY STOPPED: {exc}", file=sys.stderr)
        raise SystemExit(2)
    except Exception as exc:
        # Driver exceptions can include host/URI details. Do not print their
        # messages or tracebacks because they may contain credentials.
        print(
            "RECOVERY STOPPED: unexpected error "
            f"({type(exc).__name__}); details suppressed.",
            file=sys.stderr,
        )
        raise SystemExit(2)
